#include "engine/assets/Font.h"

namespace font {

const char kChars[] = "0123456789FPSM .:";

// 5x7, по строкам сверху вниз; в каждом байте младшие 5 бит,
// бит 4 = левый столбец. Порядок совпадает с kChars.
static const unsigned char kGlyphs[][kGlyphH] = {
    {0x0E, 0x11, 0x13, 0x15, 0x19, 0x11, 0x0E}, // 0
    {0x04, 0x0C, 0x04, 0x04, 0x04, 0x04, 0x0E}, // 1
    {0x0E, 0x11, 0x01, 0x02, 0x04, 0x08, 0x1F}, // 2
    {0x1F, 0x02, 0x04, 0x02, 0x01, 0x11, 0x0E}, // 3
    {0x02, 0x06, 0x0A, 0x12, 0x1F, 0x02, 0x02}, // 4
    {0x1F, 0x10, 0x1E, 0x01, 0x01, 0x11, 0x0E}, // 5
    {0x06, 0x08, 0x10, 0x1E, 0x11, 0x11, 0x0E}, // 6
    {0x1F, 0x01, 0x02, 0x04, 0x08, 0x08, 0x08}, // 7
    {0x0E, 0x11, 0x11, 0x0E, 0x11, 0x11, 0x0E}, // 8
    {0x0E, 0x11, 0x11, 0x0F, 0x01, 0x02, 0x0C}, // 9
    {0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x10}, // F
    {0x1E, 0x11, 0x11, 0x1E, 0x10, 0x10, 0x10}, // P
    {0x0F, 0x10, 0x10, 0x0E, 0x01, 0x01, 0x1E}, // S
    {0x11, 0x1B, 0x15, 0x15, 0x11, 0x11, 0x11}, // M
    {0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00}, // space
    {0x00, 0x00, 0x00, 0x00, 0x00, 0x0C, 0x0C}, // .
    {0x00, 0x0C, 0x0C, 0x00, 0x0C, 0x0C, 0x00}, // :
};

int glyphCount() { return (int)(sizeof(kGlyphs) / sizeof(kGlyphs[0])); }

int glyphIndex(char c) {
    for (int i = 0; kChars[i] != '\0'; ++i) {
        if (kChars[i] == c) return i;
    }
    return -1;
}

} // namespace font

TextureData makeFontAtlas() {
    int n = font::glyphCount();
    TextureData tex;
    tex.width = (uint32_t)(n * font::kGlyphW);
    tex.height = (uint32_t)font::kGlyphH;
    tex.rgba.assign((size_t)tex.width * tex.height * 4, 0);

    for (int g = 0; g < n; ++g) {
        for (int r = 0; r < font::kGlyphH; ++r) {
            for (int c = 0; c < font::kGlyphW; ++c) {
                bool on = (font::kGlyphs[g][r] >> (4 - c)) & 1;
                if (on) {
                    size_t px = ((size_t)r * tex.width + (g * font::kGlyphW + c)) * 4;
                    tex.rgba[px + 0] = 255;
                    tex.rgba[px + 1] = 255;
                    tex.rgba[px + 2] = 255;
                    tex.rgba[px + 3] = 255;
                }
            }
        }
    }
    return tex;
}
